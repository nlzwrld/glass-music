import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  buildManifestNotes,
  buildReleaseNotes,
  extractLatestChangelogSection,
} from '../../scripts/extract-changelog.mjs';

describe('GitHub Change Logs & release manifest notes', () => {
  it('extracts the latest Liquid Hub section cleanly from CHANGELOG.md without bleeding into older releases', async () => {
    const markdown = await readFile(resolve(process.cwd(), 'CHANGELOG.md'), 'utf8');
    const latest = extractLatestChangelogSection(markdown);

    expect(latest.heading).toContain('Liquid Hub');
    expect(latest.body).toContain('Cross-Platform Stream Resolver');
    expect(latest.body).toContain('Política Anti-Spam de Notificações');
    expect(latest.body).toContain('Infraestrutura JAM Híbrida');
    expect(latest.body).not.toContain('## [2.2.0]');
  });

  it('builds structured GitHub Release notes and Tauri updater manifest notes', async () => {
    const markdown = await readFile(resolve(process.cwd(), 'CHANGELOG.md'), 'utf8');
    const manifestNotes = buildManifestNotes({ version: '2.2.42', changelogMarkdown: markdown });
    const releaseNotes = buildReleaseNotes({
      version: '2.2.42',
      repository: 'nlzwrld/glass-music',
      changelogMarkdown: markdown,
      autoGeneratedNotes: '* feat: stream resolver by @nlzwrld',
    });

    expect(manifestNotes.startsWith('Liquid Hub 2.2.42\n\n')).toBe(true);
    expect(manifestNotes).toContain('track_stream_mappings');
    expect(releaseNotes).toContain('## Change Log — Liquid Hub v2.2.42');
    expect(releaseNotes).toContain('### Commits desta versão');
    expect(releaseNotes).toContain('https://github.com/nlzwrld/glass-music/blob/main/CHANGELOG.md');
  });
});
