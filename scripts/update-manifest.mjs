import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  buildManifestNotes,
  buildReleaseNotes,
  fetchGitHubGeneratedNotes,
} from './extract-changelog.mjs';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function isoTimestamp(value) {
  if (!value) throw new Error('Informe --timestamp ou RELEASE_TIMESTAMP para um manifesto reproduzível.');
  const date = new Date(value);
  if (!Number.isFinite(date.getTime())) throw new Error(`Timestamp inválido: ${value}`);
  return date.toISOString();
}

export async function createReleaseArtifacts({
  root = rootDir,
  installer,
  version,
  timestamp,
  repository = process.env.GITHUB_REPOSITORY || 'nlzwrld/glass-music',
  output = join(root, 'latest.json'),
  notesOutput = join(root, 'release-notes.md'),
  inventoryOutput = join(root, 'src-tauri', 'target', 'release', 'release-artifacts.json'),
  token = process.env.GH_TOKEN || '',
  fetchNotes = fetchGitHubGeneratedNotes,
} = {}) {
  if (!installer || !isAbsolute(installer)) throw new Error('Informe --installer com caminho absoluto.');
  if (!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version || '')) {
    throw new Error(`Versão de release inválida: ${version}`);
  }
  if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repository)) {
    throw new Error(`Repositório GitHub inválido: ${repository}`);
  }
  const pubDate = isoTimestamp(timestamp);
  const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
  if (pkg.version !== version) {
    throw new Error(`Versão divergente: package.json=${pkg.version}, release=${version}.`);
  }

  const installerBytes = await readFile(installer);
  if (!installerBytes.length) throw new Error('Instalador vazio.');
  const signaturePath = installer + '.sig';
  const signature = (await readFile(signaturePath, 'utf8')).trim();
  if (!signature) throw new Error('Assinatura do instalador vazia.');
  const assetName = basename(installer);
  if (!assetName.endsWith('-setup.exe') || !assetName.includes(`_${version}_`)) {
    throw new Error(`Nome do instalador não corresponde à versão ${version}: ${assetName}`);
  }
  const changelogPath = join(root, 'CHANGELOG.md');
  const changelogMarkdown = existsSync(changelogPath) ? await readFile(changelogPath, 'utf8') : '';
  const autoGeneratedNotes = await fetchNotes({ repository, tagName: `v${version}`, token });
  const releaseNotes = buildReleaseNotes({ version, repository, changelogMarkdown, autoGeneratedNotes });
  const manifest = {
    version,
    notes: buildManifestNotes({ version, changelogMarkdown }),
    pub_date: pubDate,
    platforms: {
      'windows-x86_64': {
        signature,
        url: `https://github.com/${repository}/releases/download/v${version}/${encodeURIComponent(assetName)}`,
      },
    },
  };

  await mkdir(dirname(output), { recursive: true });
  await mkdir(dirname(notesOutput), { recursive: true });
  await mkdir(dirname(inventoryOutput), { recursive: true });
  await writeFile(output, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
  await writeFile(notesOutput, releaseNotes, 'utf8');
  const manifestBytes = await readFile(output);
  const inventory = {
    version,
    tag: `v${version}`,
    repository,
    installer: { path: installer, name: assetName, sha256: sha256(installerBytes), size: installerBytes.length },
    signature: { path: signaturePath, name: basename(signaturePath), sha256: sha256(await readFile(signaturePath)) },
    manifest: { path: output, name: basename(output), sha256: sha256(manifestBytes), size: manifestBytes.length },
    notes: { path: notesOutput },
  };
  await writeFile(inventoryOutput, JSON.stringify(inventory, null, 2) + '\n', 'utf8');
  return { manifest, inventory, inventoryPath: inventoryOutput };
}

function arg(name, envName) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] || '' : process.env[envName] || '';
}

async function runCli() {
  const installer = arg('--installer', 'RELEASE_INSTALLER');
  const result = await createReleaseArtifacts({
    installer: installer ? resolve(installer) : '',
    version: arg('--version', 'RELEASE_VERSION'),
    timestamp: arg('--timestamp', 'RELEASE_TIMESTAMP'),
    output: resolve(arg('--output', 'RELEASE_MANIFEST') || 'latest.json'),
    notesOutput: resolve(arg('--notes-output', 'RELEASE_NOTES') || 'release-notes.md'),
    inventoryOutput: resolve(arg('--inventory', 'RELEASE_INVENTORY') || 'src-tauri/target/release/release-artifacts.json'),
  });
  process.stdout.write(`Manifesto ${result.inventory.version} e inventário gerados em ${result.inventoryPath}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await runCli();
}
