import { existsSync } from 'node:fs';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { resolve, join, basename } from 'node:path';
import {
  buildManifestNotes,
  buildReleaseNotes,
  fetchGitHubGeneratedNotes,
} from './extract-changelog.mjs';

const pkg = JSON.parse(await readFile('package.json', 'utf8'));
const repository = process.env.GITHUB_REPOSITORY || 'nlzwrld/glass-music';
const changelogMarkdown = existsSync('CHANGELOG.md') ? await readFile('CHANGELOG.md', 'utf8') : '';
const dir = resolve(process.env.CARGO_TARGET_DIR || 'src-tauri/target', 'release/bundle/nsis');
const file = (await readdir(dir)).find(f => f.includes(`_${pkg.version}_`) && f.endsWith('-setup.exe'));
if (!file) throw new Error('Signed installer missing');
const signature = (await readFile(join(dir, file + '.sig'), 'utf8')).trim();
const url = `https://github.com/${repository}/releases/download/v${pkg.version}/${encodeURIComponent(basename(file).replace(/\s/g, '.'))}`;

const autoGeneratedNotes = await fetchGitHubGeneratedNotes({
  repository,
  tagName: `v${pkg.version}`,
  token: process.env.GH_TOKEN || '',
});

await writeFile(
  'release-notes.md',
  buildReleaseNotes({
    version: pkg.version,
    repository,
    changelogMarkdown,
    autoGeneratedNotes,
  }),
  'utf8',
);

await writeFile(
  'latest.json',
  JSON.stringify(
    {
      version: pkg.version,
      notes: buildManifestNotes({ version: pkg.version, changelogMarkdown }),
      pub_date: new Date().toISOString(),
      platforms: { 'windows-x86_64': { signature, url } },
    },
    null,
    2,
  ) + '\n',
);
