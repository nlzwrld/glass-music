import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function extractLatestChangelogSection(markdown) {
  const normalized = String(markdown || '').replace(/\r\n/g, '\n');
  const lines = normalized.split('\n');
  let startIdx = -1;
  let heading = '';

  for (let i = 0; i < lines.length; i += 1) {
    if (/^##\s+\[/.test(lines[i])) {
      startIdx = i + 1;
      heading = lines[i].replace(/^##\s+/, '').trim();
      break;
    }
  }

  if (startIdx === -1) {
    return { heading: '', body: normalized.trim() };
  }

  const bodyLines = [];
  for (let i = startIdx; i < lines.length; i += 1) {
    if (/^##\s+\[/.test(lines[i])) break;
    bodyLines.push(lines[i]);
  }

  while (bodyLines.length > 0 && /^(?:---\s*)?$/.test(bodyLines[bodyLines.length - 1].trim())) {
    bodyLines.pop();
  }

  return {
    heading,
    body: bodyLines.join('\n').trim(),
  };
}

export function buildManifestNotes({ version, changelogMarkdown }) {
  const { body } = extractLatestChangelogSection(changelogMarkdown);
  if (!body) return `Liquid Hub ${version}`;
  return `Liquid Hub ${version}\n\n${body}`;
}

export function buildReleaseNotes({
  version,
  repository = 'nlzwrld/glass-music',
  changelogMarkdown,
  autoGeneratedNotes = '',
}) {
  const { body } = extractLatestChangelogSection(changelogMarkdown);
  const parts = [`## Change Log — Liquid Hub v${version}`];
  if (body) {
    parts.push(body);
  }
  if (autoGeneratedNotes && autoGeneratedNotes.trim()) {
    parts.push('---\n\n### Commits desta versão\n\n' + autoGeneratedNotes.trim());
  }
  parts.push(
    `---\nHistórico completo: [\`CHANGELOG.md\`](https://github.com/${repository}/blob/main/CHANGELOG.md)`,
  );
  return parts.join('\n\n') + '\n';
}

export async function fetchGitHubGeneratedNotes({ repository, tagName, token }) {
  if (!token || !repository || !tagName) return '';
  try {
    const res = await fetch(`https://api.github.com/repos/${repository}/releases/generate-notes`, {
      method: 'POST',
      headers: {
        Accept: 'application/vnd.github+json',
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
        'User-Agent': 'LiquidHub-Release/2.2',
      },
      body: JSON.stringify({ tag_name: tagName, target_commitish: 'main' }),
      signal: AbortSignal.timeout(15_000),
    });
    if (!res.ok) return '';
    const payload = await res.json();
    return typeof payload?.body === 'string' ? payload.body : '';
  } catch {
    return '';
  }
}

async function runCli() {
  const pkg = JSON.parse(await readFile(resolve(rootDir, 'package.json'), 'utf8'));
  const changelogMarkdown = await readFile(resolve(rootDir, 'CHANGELOG.md'), 'utf8');
  const repository = process.env.GITHUB_REPOSITORY || 'nlzwrld/glass-music';
  const outIdx = process.argv.indexOf('--out');
  const outPath = outIdx !== -1 && process.argv[outIdx + 1] ? process.argv[outIdx + 1] : '';
  const autoGeneratedNotes = await fetchGitHubGeneratedNotes({
    repository,
    tagName: `v${pkg.version}`,
    token: process.env.GH_TOKEN || '',
  });
  const rendered = buildReleaseNotes({
    version: pkg.version,
    repository,
    changelogMarkdown,
    autoGeneratedNotes,
  });
  if (outPath) {
    await writeFile(outPath, rendered, 'utf8');
  } else {
    process.stdout.write(rendered);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await runCli();
}
